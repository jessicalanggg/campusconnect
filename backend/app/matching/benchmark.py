"""Compare greedy, local search and ILP on synthetic populations.

    python -m app.matching.benchmark                 # print a markdown table
    python -m app.matching.benchmark --out ../docs/benchmark.md

The populations are SYNTHETIC (see synthetic.py). Use the numbers to compare algorithms, not as usage claims;
real-run comparisons are recorded per course in the match_runs table and summarised at /api/metrics.
"""
import argparse
import statistics

from app.matching.engine import MatchConfig, solve_all
from app.matching.synthetic import generate

SIZES = (30, 60, 120, 250)
SEEDS = (1, 2, 3, 4, 5)


def run(sizes=SIZES, seeds=SEEDS, cfg: MatchConfig | None = None) -> str:
    cfg = cfg or MatchConfig()
    lines = [
        "| Students | Algorithm | Placed | Avg quality | Avg shared hrs/week | Runtime (ms) |",
        "|---:|---|---:|---:|---:|---:|",
    ]
    gains_q, gains_h = [], []
    for n in sizes:
        agg: dict[str, list[dict]] = {}
        for seed in seeds:
            for name, (_, ev) in solve_all(generate(n, seed), cfg).items():
                agg.setdefault(name, []).append(ev)
        for name in ("greedy", "local_search", "ilp"):
            evs = agg[name]
            lines.append(f"| {n} | {name} | {statistics.mean(e['coverage'] for e in evs):.1%} "
                         f"| {statistics.mean(e['avg_quality'] for e in evs):.3f} "
                         f"| {statistics.mean(e['avg_common_hours'] for e in evs):.2f} "
                         f"| {statistics.mean(e['runtime_ms'] for e in evs):.0f} |")
        gq = statistics.mean(e["avg_quality"] for e in agg["greedy"])
        iq = statistics.mean(e["avg_quality"] for e in agg["ilp"])
        gh = statistics.mean(e["avg_common_hours"] for e in agg["greedy"])
        ih = statistics.mean(e["avg_common_hours"] for e in agg["ilp"])
        gains_q.append((n, 100 * (iq - gq) / gq))
        gains_h.append((n, 100 * (ih - gh) / gh))
    summary = ["", "ILP vs greedy (mean of seeds):", ""]
    summary += [f"- {n} students: match quality {q:+.1f}%, shared free time {h:+.1f}%"
                for (n, q), (_, h) in zip(gains_q, gains_h)]
    return "\n".join(lines + summary)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out")
    args = parser.parse_args()
    table = run()
    header = (
        "# Matching benchmark\n\n"
        "Generated by `python -m app.matching.benchmark`. Populations are **synthetic** "
        f"({len(SEEDS)} seeds per size; see `app/matching/synthetic.py`), so these numbers compare algorithms "
        "under identical conditions. They are not usage results. Placed = share of students put in a feasible "
        "group (size 3–6, at least 2 shared free hours per week). Quality is per student in [0, 1]: 40% shared "
        "time, 25% goal match, 15% pace match, 20% size preference.\n\n"
    )
    out = header + table + "\n"
    if args.out:
        with open(args.out, "w") as f:
            f.write(out)
    print(out)


if __name__ == "__main__":
    main()
